        normalized = normalize_text(text)
        hits: dict[str, list[str]] = {}
        for code, pattern in self.compiled:
            terms = sorted({match.group(0) for match in pattern.finditer(normalized)})
            if terms:
                hits[code] = terms[:10]
        return hits
